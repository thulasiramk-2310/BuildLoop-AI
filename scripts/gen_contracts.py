"""Generate TypeScript contract types from the backend Pydantic models.

Usage: .venv/Scripts/python scripts/gen_contracts.py   (writes packages/contracts/index.ts and apps/web/src/types.ts)
CI/tests compare the output with the committed file to catch frontend/backend drift.
"""
from __future__ import annotations

import enum
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "api"))

from buildloop import models as m
from buildloop.workflow import ProjectState
from pydantic import BaseModel


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return repr(schema["const"]).replace("'", '"')
    if "enum" in schema:
        return " | ".join(f'"{v}"' for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(s) for s in schema["anyOf"]))
    t = schema.get("type")
    if t == "array":
        items = schema.get("items")
        if "prefixItems" in schema:
            return "[" + ", ".join(ts_type(s) for s in schema["prefixItems"]) + "]"
        return f"({ts_type(items)})[]" if items else "unknown[]"
    if t == "object":
        ap = schema.get("additionalProperties")
        if isinstance(ap, dict):
            return f"Record<string, {ts_type(ap)}>"
        return "Record<string, unknown>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(t, "unknown")


def emit_model(name: str, schema: dict) -> str:
    if "enum" in schema:
        return f"export type {name} = " + " | ".join(f'"{v}"' for v in schema["enum"]) + ";"
    # The API always serializes complete models, so every field is present (possibly null).
    lines = [f"export interface {name} {{"]
    for prop, ps in schema.get("properties", {}).items():
        lines.append(f"  {prop}: {ts_type(ps)};")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    classes = [
        c for _, c in vars(m).items()
        if isinstance(c, type) and c.__module__ == m.__name__ and (issubclass(c, BaseModel) or issubclass(c, enum.Enum))
    ] + [ProjectState]
    defs: dict[str, dict] = {}
    for c in classes:
        if issubclass(c, BaseModel):
            schema = c.model_json_schema(mode="serialization", ref_template="#/$defs/{model}")
            defs.update(schema.get("$defs", {}))
            defs[c.__name__] = {k: v for k, v in schema.items() if k != "$defs"}
        else:
            defs[c.__name__] = {"enum": [e.value for e in c]}
    out = ["// GENERATED by scripts/gen_contracts.py from apps/api/buildloop/models.py. Do not edit.\n"]
    for name in sorted(defs):
        out.append(emit_model(name, defs[name]))
    text = "\n\n".join(out) + "\n"
    for target in (ROOT / "packages" / "contracts" / "index.ts", ROOT / "apps" / "web" / "src" / "types.ts"):
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    print(f"wrote {len(defs)} types")


if __name__ == "__main__":
    main()
